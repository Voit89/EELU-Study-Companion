import type { Lesson, LessonBlock, LessonPage } from '../types';

function explainedPage(
  sourcePage: number,
  title: string,
  takeaway: string,
  explanation: string,
  terms?: string,
  note?: string,
  trap?: string,
): LessonPage {
  const blocks: LessonBlock[] = [{ type: 'zobda', text: takeaway }];
  if (terms) {
    blocks.push({ type: 'recognition', title: 'مصطلحات الصفحة', markdown: terms });
  }
  blocks.push({ type: 'foundation', title: 'الفكرة خطوةً خطوة', markdown: explanation });
  if (trap) {
    blocks.push({ type: 'trap', title: 'انتبه إلى هذا الفرق', markdown: trap });
  }
  return { sourcePage, title, coverage: 'explained', blocks, ...(note ? { note } : {}) };
}

